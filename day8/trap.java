// 给定 n 个非负整数表示每个宽度为 1 的柱子的高度图，计算按此排列的柱子，下雨之后能接多少雨水。
// 示例 1：
// 输入：height = [0,1,0,2,1,0,1,3,2,1,2,1]
// 输出：6
// 解释：上面是由数组 [0,1,0,2,1,0,1,3,2,1,2,1] 表示的高度图，在这种情况下，可以接 6 个单位的雨水（蓝色部分表示雨水）。 
// 示例 2：
// 输入：height = [4,2,0,3,2,5]
// 输出：9
// 提示：
// n == height.length
// 1 <= n <= 2 * 104
// 0 <= height[i] <= 105

//我的想法:首先我们用一个指针去找第一个非0的柱子,然后另一个指针从这里去找界限
//假如更高的话[1,3]这种长度为1的就存不了水
//假如更低的话[1.0]这种就可以继续往后找,直到找到为1或者更高的柱子,这中间的区域就可以判定为可蓄水,然后判断一下可以蓄水多少就行
//预估时间是n+中间判定的时间,应该可以接受,方法应该是可行的
//[0,1,0,2,1,0,1,3,2,1,2,1]->[1,0,2],中间蓄水1;[2,1,0,1,3]中间蓄水,判定蓄水1+2+1=4;[3,2,1,2,1]中间蓄水,判定蓄水为1
//蓄水判定-边界差值,比如2-1->1,1-0=1;3-2->2,(2-1) + (2-0) + (2-1); 3-1->1,2>1,1=1,等等这就出问题了,需要优化判定
//水池边界判定优化为最低值的判定,原先[3,2,1,2,1]改为[3,2,1,2]的判定这样蓄水就正常了
class Solution {
    public int trap(int[] height) {
        int left = 0;
        int right = height.length - 1;
        int leftMax = 0;
        int rightMax = 0;
        int sum = 0;

        while (left < right) {
            if (height[left] < height[right]) {
                // 左边更矮，结算左边
                leftMax = Math.max(leftMax, height[left]);
                sum += leftMax - height[left];
                left++;
            } else {
                // 右边更矮（或相等），结算右边
                rightMax = Math.max(rightMax, height[right]);
                sum += rightMax - height[right];
                right--;
            }
        }
        return sum;
    }
}